"""Builds docs/sil_results.md from real SIL runs (numbers are never typed by hand)."""
from sil.scenarios import SCENARIOS, run
from visualization.sil_plots import plot_scenario

DESC = {"nominal": "No fault; drive started at 1.2 s, torque request 60 Nm.",
        "f01_single_frame_loss": "F01 - one BRAKE_Status frame lost (below the 60 ms timeout).",
        "f02_brake_timeout": "F02 - BRAKE_Status absent for 500 ms.",
        "f03_speed_invalid": "F03 - VehicleSpeed carries its invalid value for 800 ms.",
        "f04_voltage_out_of_range": "F04 - BatteryVoltage 600 V (range 0-500 V) for 500 ms.",
        "f05_bms_unavailable": "F05 - BMS_ECU unavailable for 1.5 s.",
        "f07a_counter_fault": "F07a - alive counter frozen on VehicleDynamics for 100 ms.",
        "f07b_crc_fault": "F07b - CRC corrupted on VehicleDynamics for 100 ms.",
        "brake_override": "Brake pedal applied 3.0-4.0 s while 60 Nm is requested."}


def build(fig_dir, doc_path):
    lines = ["# Python SIL results (SIMULATED)", "",
             "Generated by `python python/main.py sil-report`. Every number below comes from an executed run of the Python port of the "
             "ECU design on a simulated-time bus. These are **not** CANoe measurements and **not** vehicle tests.", "",
             "| Scenario | Fault | DTC events (first set / healed, powertrain ECU) |", "|---|---|---|"]
    sections = []
    for name in SCENARIOS:
        r = run(name)
        plot_scenario(r, fig_dir / f"sil_{name}.png")
        pt = [e for e in r.sim.events if e[1] == "POWERTRAIN_ECU"]
        ev = "; ".join(f"{e[2].split(' (')[0]} @ {e[0]} ms" for e in pt) or "none"
        lines.append(f"| `{name}` | {DESC[name]} | {ev} |")
        sections.append(f"## {name}\n{DESC[name]}\n\n![{name}](figures/sil_{name}.png)\n")
    doc_path.write_text("\n".join(lines) + "\n\n" + "\n".join(sections))
